def valid_xyz(value) -> Optional[np.ndarray]:
    """
    Convert `value` to a finite XYZ vector.

    Returns None when the value is unavailable, malformed, contains NaN, or
    contains infinity.
    """
    if value is None:
        return None

    array = np.asarray(value, dtype=np.float32).reshape(-1)

    if array.size < 3:
        return None

    xyz = array[:3].copy()

    if xyz.shape != (3,) or not np.all(np.isfinite(xyz)):
        return None

    return xyz


def yes_no(value: bool) -> str:
    return "YES" if bool(value) else "NO"


def frame_or_na(frame: int) -> str:
    return str(frame) if frame >= 0 else "N/A"


def finite_or_na(
    value: float,
    scale: float = 1.0,
    precision: int = 3,
    signed: bool = False,
) -> str:
    """Format a floating-point value safely for metrics output."""
    if value is None or not np.isfinite(value):
        return "N/A"

    format_specifier = (
        f"+.{precision}f"
        if signed
        else f".{precision}f"
    )

    return format(value * scale, format_specifier)


def load_human_video(video_path: str) -> np.ndarray:
    """Load an MP4 as an RGB uint8 array."""
    path = Path(video_path)

    if not path.exists():
        raise FileNotFoundError(
            f"Human video not found: {path}"
        )

    capture = cv2.VideoCapture(str(path))

    if not capture.isOpened():
        raise RuntimeError(
            f"Could not open human video: {path}"
        )

    frames = []

    while True:
        success, frame_bgr = capture.read()

        if not success:
            break

        frames.append(
            cv2.cvtColor(
                frame_bgr,
                cv2.COLOR_BGR2RGB,
            )
        )

    capture.release()

    if not frames:
        raise RuntimeError(
            f"No frames were decoded from: {path}"
        )

    frames_array = np.asarray(
        frames,
        dtype=np.uint8,
    )

    print(
        f"[+] Loaded {len(frames_array)} human frames "
        f"from: {path}"
    )

    return frames_array


def calculate_replay_fps(data) -> float:
    """Determine replay FPS from stored FPS or timestamps."""
    replay_fps = DEFAULT_REPLAY_FPS

    if "fps" in data:
        candidate = float(
            np.asarray(data["fps"]).item()
        )

        if np.isfinite(candidate) and candidate > 0.0:
            replay_fps = candidate

    elif "timestamps" in data:
        timestamps = np.asarray(
            data["timestamps"],
            dtype=np.float64,
        )

        if len(timestamps) > 1:
            time_differences = np.diff(timestamps)
            valid_differences = time_differences[
                np.isfinite(time_differences)
                & (time_differences > 0.0)
            ]

            if len(valid_differences) > 0:
                median_dt = float(
                    np.median(valid_differences)
                )
                replay_fps = 1.0 / median_dt

    if (
        not np.isfinite(replay_fps)
        or replay_fps <= 0.0
    ):
        replay_fps = DEFAULT_REPLAY_FPS

    return replay_fps



def create_comparison_video(
    sim_frames: np.ndarray,
    human_frames: Optional[np.ndarray],
    output_video_path: str,
    replay_fps: float,
) -> None:
    """Create a 512x256 human/simulation comparison video."""
    output_path = Path(output_video_path)
    output_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    writer = cv2.VideoWriter(
        str(output_path),
        cv2.VideoWriter_fourcc(*"mp4v"),
        replay_fps,
        (512, 256),
    )

    if not writer.isOpened():
        raise RuntimeError(
            f"Could not create video: {output_path}"
        )

    if human_frames is not None:
        number_of_frames = min(
            len(sim_frames),
            len(human_frames),
        )
    else:
        number_of_frames = len(sim_frames)

    for frame_index in range(number_of_frames):
        sim_rgb = np.asarray(
            sim_frames[frame_index],
            dtype=np.uint8,
        )

        sim_rgb = cv2.resize(
            sim_rgb,
            (256, 256),
            interpolation=cv2.INTER_AREA,
        )

        sim_bgr = cv2.cvtColor(
            sim_rgb,
            cv2.COLOR_RGB2BGR,
        )

        if human_frames is not None:
            human_rgb = cv2.resize(
                human_frames[frame_index],
                (256, 256),
                interpolation=cv2.INTER_AREA,
            )

            human_bgr = cv2.cvtColor(
                human_rgb,
                cv2.COLOR_RGB2BGR,
            )
        else:
            human_bgr = np.zeros_like(sim_bgr)

        comparison_frame = np.hstack(
            [human_bgr, sim_bgr]
        )

        writer.write(comparison_frame)

    writer.release()

    print(
        f"[+] Saved synchronized video: {output_path}"
    )


