def replay_actions_and_record(
    actions_npz_path: str,
    output_video_path: str,
    output_dataset_path: Optional[str] = None,
    task_name: str = "Lift",
    render_gui: bool = False,
    human_video_path: Optional[str] = None,
    closed_loop_pregrasp: bool = False,
    target_eef_x: float = -0.050,
    pregrasp_kp_x: float = 4.0,
    pregrasp_max_correction: float = 0.07,
    pregrasp_deadband_m: float = 0.002,
    target_eef_z: float = 0.855,
    pregrasp_kp_z: float = 3.0,
    pregrasp_max_z_correction: float = 0.05,
    pregrasp_z_deadband_m: float = 0.002,
    pregrasp_control_start_frac: float = 0.65,
) -> None:
    """Replay Panda actions with optional closed-loop pre-grasp X/Z correction."""

    # -------------------------------------------------------------------------
    # 1. VALIDATE CONTROLLER SETTINGS
    # -------------------------------------------------------------------------
    values = {
        "target_eef_x": target_eef_x,
        "pregrasp_kp_x": pregrasp_kp_x,
        "pregrasp_max_correction": pregrasp_max_correction,
        "pregrasp_deadband_m": pregrasp_deadband_m,
        "target_eef_z": target_eef_z,
        "pregrasp_kp_z": pregrasp_kp_z,
        "pregrasp_max_z_correction": pregrasp_max_z_correction,
        "pregrasp_z_deadband_m": pregrasp_z_deadband_m,
        "pregrasp_control_start_frac": pregrasp_control_start_frac,
    }

    for name, value in values.items():
        if not np.isfinite(value):
            raise ValueError(f"{name} must be finite.")

    if pregrasp_kp_x < 0 or pregrasp_kp_z < 0:
        raise ValueError("X and Z gains must be non-negative.")
    if not 0 < pregrasp_max_correction <= 1:
        raise ValueError("pregrasp_max_correction must be in (0, 1].")
    if not 0 < pregrasp_max_z_correction <= 1:
        raise ValueError("pregrasp_max_z_correction must be in (0, 1].")
    if pregrasp_deadband_m < 0 or pregrasp_z_deadband_m < 0:
        raise ValueError("X and Z deadbands must be non-negative.")
    if not 0 <= pregrasp_control_start_frac < 1:
        raise ValueError("pregrasp_control_start_frac must be in [0, 1).")

    # -------------------------------------------------------------------------
    # 2. LOAD SOURCE TRAJECTORY
    # -------------------------------------------------------------------------
    actions_file = Path(actions_npz_path)
    if not actions_file.exists():
        raise FileNotFoundError(f"Actions file not found: {actions_file}")

    with np.load(actions_file, allow_pickle=False) as data:
        if "actions" not in data:
            raise KeyError(f"No 'actions' array in {actions_file}")

        source_actions = np.asarray(data["actions"], dtype=np.float32).copy()
        if source_actions.ndim != 2 or source_actions.shape[1] != 7:
            raise ValueError(f"Expected actions shape (T, 7), got {source_actions.shape}")
        if not np.all(np.isfinite(source_actions)):
            raise ValueError("Source actions contain NaN or infinity.")

        replay_fps = calculate_replay_fps(data)
        entry_frame = int(np.asarray(data["entry_frame"]).item()) if "entry_frame" in data else 0
        stored_rgb_frames = None
        if human_video_path is None and "rgb_frames" in data:
            stored_rgb_frames = np.asarray(data["rgb_frames"], dtype=np.uint8).copy()

    human_frames = load_human_video(human_video_path) if human_video_path else stored_rgb_frames
    number_of_steps = len(source_actions)

    # -------------------------------------------------------------------------
    # 3. DETERMINE CONTROL WINDOW
    # -------------------------------------------------------------------------
    grasp_indices = np.where(source_actions[:, 6] > 0.0)[0]
    commanded_grasp_frame = int(grasp_indices[0]) if len(grasp_indices) else number_of_steps
    entry_frame = int(np.clip(entry_frame, 0, max(0, commanded_grasp_frame - 1)))
    approach_duration = max(1, commanded_grasp_frame - entry_frame)
    pregrasp_control_start = entry_frame + int(pregrasp_control_start_frac * approach_duration)
    pregrasp_control_start = int(np.clip(pregrasp_control_start, entry_frame, max(entry_frame, commanded_grasp_frame - 1)))

    print(f"[*] Replaying {number_of_steps} steps in '{task_name}'")
    print(f"[*] FPS: {replay_fps:.2f}, entry: {entry_frame}, grasp command: {commanded_grasp_frame}")

    if closed_loop_pregrasp:
        print("[*] Closed-loop pre-grasp X/Z: ENABLED")
        print(f"[*] Targets: X={target_eef_x:+.4f} m, Z={target_eef_z:+.4f} m")
        print(f"[*] Control window: {pregrasp_control_start} -> {commanded_grasp_frame - 1}")
    else:
        print("[*] Closed-loop pre-grasp X/Z: DISABLED")

    # -------------------------------------------------------------------------
    # 4. CREATE SIMULATION
    # -------------------------------------------------------------------------
    env = PandaSimEnvironment(
        env_name=task_name,
        has_renderer=render_gui,
        has_offscreen_renderer=True,
        camera_name="agentview",
        camera_height=256,
        camera_width=256,
    )

    obs = env.reset()
    print("[*] Observation keys:", sorted(obs.keys()))

    initial_eef_pos = valid_xyz(obs.get("robot_eef_pos"))
    current_eef_pos = initial_eef_pos.copy() if initial_eef_pos is not None else None
    initial_tumbler_pos = valid_xyz(obs.get("tumbler_pos"))
    tumbler_pos_source = obs.get("tumbler_pos_source")
    left_pad_geom_name = obs.get("left_finger_pad_geom")
    right_pad_geom_name = obs.get("right_finger_pad_geom")
    glass_radius = float(obs.get("glass_radius", 0.030))

    print(f"[PHYSICS] Initial EEF XYZ: {initial_eef_pos}")
    print(f"[PHYSICS] Initial tumbler XYZ: {initial_tumbler_pos}")
    print(f"[PHYSICS] Tumbler source: {tumbler_pos_source}")

    # -------------------------------------------------------------------------
    # 5. STORAGE
    # -------------------------------------------------------------------------
    sim_frames = []
    eef_positions_list, eef_frames_list = [], []
    tumbler_positions_list, tumbler_frames_list = [], []
    left_pad_list, right_pad_list = [], []
    contacts, grasps, rewards = [], [], []
    executed_actions_list = []
    x_errors_list, x_corrections_list = [], []
    z_errors_list, z_corrections_list = [], []
    control_active_list = []

    # -------------------------------------------------------------------------
    # 6. REPLAY WITH CLOSED-LOOP X/Z CORRECTION
    # -------------------------------------------------------------------------
    try:
        for frame_index in range(number_of_steps):
            source_action = source_actions[frame_index].copy()
            executed_action = source_action.copy()

            x_error = z_error = np.nan
            x_correction = z_correction = 0.0
            control_active = False

            if closed_loop_pregrasp and current_eef_pos is not None and pregrasp_control_start <= frame_index < commanded_grasp_frame:
                control_active = True
                x_error = float(target_eef_x - current_eef_pos[0])
                z_error = float(target_eef_z - current_eef_pos[2])

                if abs(x_error) > pregrasp_deadband_m:
                    x_correction = float(np.clip(pregrasp_kp_x * x_error, -pregrasp_max_correction, pregrasp_max_correction))
                if abs(z_error) > pregrasp_z_deadband_m:
                    z_correction = float(np.clip(pregrasp_kp_z * z_error, -pregrasp_max_z_correction, pregrasp_max_z_correction))

                executed_action[0] = float(np.clip(source_action[0] + x_correction, -1.0, 1.0))
                executed_action[2] = float(np.clip(source_action[2] + z_correction, -1.0, 1.0))

            obs, reward, done, info = env.step(executed_action)

            measured_eef_pos = valid_xyz(obs.get("robot_eef_pos"))
            tumbler_pos = valid_xyz(obs.get("tumbler_pos"))
            left_pad_pos = valid_xyz(obs.get("left_finger_pad_pos"))
            right_pad_pos = valid_xyz(obs.get("right_finger_pad_pos"))

            if measured_eef_pos is not None:
                current_eef_pos = measured_eef_pos.copy()
                eef_positions_list.append(measured_eef_pos.copy())
                eef_frames_list.append(frame_index)

            if tumbler_pos is not None:
                tumbler_positions_list.append(tumbler_pos.copy())
                tumbler_frames_list.append(frame_index)

            left_pad_list.append(left_pad_pos.copy() if left_pad_pos is not None else np.full(3, np.nan, dtype=np.float32))
            right_pad_list.append(right_pad_pos.copy() if right_pad_pos is not None else np.full(3, np.nan, dtype=np.float32))

            contact_value = obs.get("tumbler_contact")
            grasp_value = obs.get("tumbler_grasped")
            contact_float = float(contact_value) if contact_value is not None else np.nan
            grasp_float = float(grasp_value) if grasp_value is not None else np.nan

            contacts.append(contact_float)
            grasps.append(grasp_float)
            rewards.append(float(reward))
            executed_actions_list.append(executed_action.copy())
            x_errors_list.append(x_error)
            x_corrections_list.append(x_correction)
            z_errors_list.append(z_error)
            z_corrections_list.append(z_correction)
            control_active_list.append(control_active)

            rgb_frame = obs.get("rgb")
            if rgb_frame is not None:
                sim_frames.append(np.asarray(rgb_frame, dtype=np.uint8).copy())

            phase = "CL-XZ" if control_active else "SOURCE"
            eef_text = np.array2string(measured_eef_pos, precision=4) if measured_eef_pos is not None else "N/A"
            tumbler_text = np.array2string(tumbler_pos, precision=4) if tumbler_pos is not None else "N/A"
            x_text = f"{x_error:+.5f}" if np.isfinite(x_error) else "N/A"
            z_text = f"{z_error:+.5f}" if np.isfinite(z_error) else "N/A"

            print(
                f"[REPLAY] frame={frame_index:04d} phase={phase} "
                f"source=[{source_action[0]:+.3f},{source_action[1]:+.3f},{source_action[2]:+.3f}] "
                f"executed=[{executed_action[0]:+.3f},{executed_action[1]:+.3f},{executed_action[2]:+.3f}] "
                f"x_err={x_text} x_corr={x_correction:+.3f} z_err={z_text} z_corr={z_correction:+.3f} "
                f"grip={executed_action[6]:+.1f} eef={eef_text} tumbler={tumbler_text} "
                f"contact={contact_float} grasp={grasp_float} reward={float(reward):.4f}"
            )

            if render_gui:
                env.render()
            if done:
                print(f"[*] done=True at frame {frame_index}; continuing for synchronized analysis.")
    finally:
        env.close()

    print(f"[+] Replay complete. Captured {len(sim_frames)} simulation frames.")

    # -------------------------------------------------------------------------
    # 7. CONVERT RECORDINGS TO ARRAYS
    # -------------------------------------------------------------------------
    executed_actions = np.asarray(executed_actions_list, dtype=np.float32)
    rewards = np.asarray(rewards, dtype=np.float32)
    eef_positions = np.asarray(eef_positions_list, dtype=np.float32)
    eef_position_frames = np.asarray(eef_frames_list, dtype=np.int32)
    tumbler_positions = np.asarray(tumbler_positions_list, dtype=np.float32)
    tumbler_position_frames = np.asarray(tumbler_frames_list, dtype=np.int32)
    left_pad_positions = np.asarray(left_pad_list, dtype=np.float32)
    right_pad_positions = np.asarray(right_pad_list, dtype=np.float32)
    contact_flags = np.asarray(contacts, dtype=np.float32)
    grasp_flags = np.asarray(grasps, dtype=np.float32)
    x_errors = np.asarray(x_errors_list, dtype=np.float32)
    x_corrections = np.asarray(x_corrections_list, dtype=np.float32)
    z_errors = np.asarray(z_errors_list, dtype=np.float32)
    z_corrections = np.asarray(z_corrections_list, dtype=np.float32)
    control_active_mask = np.asarray(control_active_list, dtype=np.bool_)

    # -------------------------------------------------------------------------
    # 8. GENERAL METRICS
    # -------------------------------------------------------------------------
    final_eef_pos = eef_positions[-1].copy() if len(eef_positions) else None
    max_eef_dx = max_eef_dy = max_eef_dz = np.nan

    if len(eef_positions) and initial_eef_pos is not None:
        eef_displacements = eef_positions - initial_eef_pos[None, :]
        max_eef_dx = float(np.max(np.abs(eef_displacements[:, 0])))
        max_eef_dy = float(np.max(np.abs(eef_displacements[:, 1])))
        max_eef_dz = float(np.max(np.abs(eef_displacements[:, 2])))

    maximum_tumbler_lift = np.nan
    lift_success = None

    if len(tumbler_positions) and initial_tumbler_pos is not None:
        maximum_tumbler_lift = float(np.max(tumbler_positions[:, 2]) - initial_tumbler_pos[2])
        lift_success = bool(maximum_tumbler_lift >= LIFT_SUCCESS_THRESHOLD_M)

    contact_indices = np.where(contact_flags > 0.5)[0]
    grasp_indices_actual = np.where(grasp_flags > 0.5)[0]
    contact_occurred = len(contact_indices) > 0
    grasp_occurred = len(grasp_indices_actual) > 0
    first_contact_frame = int(contact_indices[0]) if contact_occurred else -1
    first_grasp_frame = int(grasp_indices_actual[0]) if grasp_occurred else -1
    active_control_frames = int(np.count_nonzero(control_active_mask))

    def control_stats(errors: np.ndarray, corrections: np.ndarray):
        finite_errors = errors[np.isfinite(errors)]
        initial = float(finite_errors[0]) if len(finite_errors) else np.nan
        final = float(finite_errors[-1]) if len(finite_errors) else np.nan
        minimum = float(np.min(np.abs(finite_errors))) if len(finite_errors) else np.nan
        maximum_correction = float(np.max(np.abs(corrections))) if len(corrections) else np.nan
        return initial, final, minimum, maximum_correction

    initial_x_error, final_x_error, minimum_x_error, maximum_x_correction = control_stats(x_errors, x_corrections)
    initial_z_error, final_z_error, minimum_z_error, maximum_z_correction = control_stats(z_errors, z_corrections)

    # -------------------------------------------------------------------------
    # 9. EEF / TUMBLER CLOSEST GEOMETRY
    # -------------------------------------------------------------------------
    eef_by_frame = {int(frame): pos for frame, pos in zip(eef_position_frames, eef_positions)}
    tumbler_by_frame = {int(frame): pos for frame, pos in zip(tumbler_position_frames, tumbler_positions)}
    common_frames = sorted(set(eef_by_frame).intersection(tumbler_by_frame))

    minimum_eef_object_distance = np.nan
    closest_approach_frame = -1
    closest_eef_pos = closest_tumbler_pos = None

    if common_frames:
        paired_eef = np.asarray([eef_by_frame[f] for f in common_frames], dtype=np.float32)
        paired_tumbler = np.asarray([tumbler_by_frame[f] for f in common_frames], dtype=np.float32)
        distances = np.linalg.norm(paired_eef - paired_tumbler, axis=1)
        closest_index = int(np.argmin(distances))
        minimum_eef_object_distance = float(distances[closest_index])
        closest_approach_frame = int(common_frames[closest_index])
        closest_eef_pos = paired_eef[closest_index]
        closest_tumbler_pos = paired_tumbler[closest_index]

    # -------------------------------------------------------------------------
    # 10. FINGER-PAD GEOMETRY
    # -------------------------------------------------------------------------
    diagnostic = {"available": False}
    tumbler_full = np.full((number_of_steps, 3), np.nan, dtype=np.float32)

    for frame, position in zip(tumbler_position_frames, tumbler_positions):
        if 0 <= frame < number_of_steps:
            tumbler_full[int(frame)] = position

    n = min(number_of_steps, len(left_pad_positions), len(right_pad_positions))

    if n:
        left_valid = np.all(np.isfinite(left_pad_positions[:n]), axis=1)
        right_valid = np.all(np.isfinite(right_pad_positions[:n]), axis=1)
        tumbler_valid = np.all(np.isfinite(tumbler_full[:n]), axis=1)
        valid_left = left_valid & tumbler_valid
        valid_right = right_valid & tumbler_valid

        if np.any(valid_left) and np.any(valid_right):
            left_frames = np.where(valid_left)[0]
            right_frames = np.where(valid_right)[0]
            left_distances = np.linalg.norm(left_pad_positions[left_frames] - tumbler_full[left_frames], axis=1)
            right_distances = np.linalg.norm(right_pad_positions[right_frames] - tumbler_full[right_frames], axis=1)
            li, ri = int(np.argmin(left_distances)), int(np.argmin(right_distances))
            lf, rf = int(left_frames[li]), int(right_frames[ri])
            left_horizontal = float(np.linalg.norm(left_pad_positions[lf, :2] - tumbler_full[lf, :2]))
            right_horizontal = float(np.linalg.norm(right_pad_positions[rf, :2] - tumbler_full[rf, :2]))

            diagnostic = {
                "available": True,
                "left_pad_geom_name": left_pad_geom_name,
                "right_pad_geom_name": right_pad_geom_name,
                "glass_diameter": 2.0 * glass_radius,
                "left_closest_frame": lf,
                "right_closest_frame": rf,
                "left_pad_xyz": left_pad_positions[lf],
                "right_pad_xyz": right_pad_positions[rf],
                "min_left_pad_dist": float(left_distances[li]),
                "min_right_pad_dist": float(right_distances[ri]),
                "left_horizontal_to_axis": left_horizontal,
                "right_horizontal_to_axis": right_horizontal,
                "left_vertical_offset": float(left_pad_positions[lf, 2] - tumbler_full[lf, 2]),
                "right_vertical_offset": float(right_pad_positions[rf, 2] - tumbler_full[rf, 2]),
                "left_surface_clearance": left_horizontal - glass_radius - PAD_HALF_THICKNESS_M,
                "right_surface_clearance": right_horizontal - glass_radius - PAD_HALF_THICKNESS_M,
            }

            grasp_window_start = max(0, commanded_grasp_frame - 10)
            grasp_window_end = min(n, commanded_grasp_frame + 30)
            window_frames = np.arange(grasp_window_start, grasp_window_end, dtype=np.int32)
            window_valid = left_valid[window_frames] & right_valid[window_frames]
            valid_window_frames = window_frames[window_valid]

            if len(valid_window_frames) > 0:
                separations = np.linalg.norm(
                    left_pad_positions[valid_window_frames]
                    - right_pad_positions[valid_window_frames],
                    axis=1,
                )
                separation_index = int(np.argmin(separations))
                diagnostic["min_pad_separation_episode"] = float(separations[separation_index])
                diagnostic["min_pad_separation_frame"] = int(valid_window_frames[separation_index])
            else:
                diagnostic["min_pad_separation_episode"] = np.nan
                diagnostic["min_pad_separation_frame"] = -1

    # -------------------------------------------------------------------------
    # 11. SAVE METRICS
    # -------------------------------------------------------------------------
    output_video = Path(output_video_path)
    output_video.parent.mkdir(parents=True, exist_ok=True)
    metrics_path = output_video.parent / "metrics.txt"

    with open(metrics_path, "w", encoding="utf-8") as f:
        f.write("REPLAY METRICS\n" + "=" * 68 + "\n\n")
        f.write("INPUT / REPLAY\n" + "-" * 68 + "\n")
        f.write(f"Actions file:              {actions_file}\n")
        f.write(f"Task:                      {task_name}\n")
        f.write(f"Action steps:              {number_of_steps}\n")
        f.write(f"Comparison FPS:            {replay_fps:.2f}\n\n")

        f.write("CLOSED-LOOP PRE-GRASP X/Z CONTROL\n" + "-" * 68 + "\n")
        f.write(f"Enabled:                   {yes_no(closed_loop_pregrasp)}\n")
        f.write(f"Control window:            {pregrasp_control_start} to {commanded_grasp_frame - 1}\n")
        f.write(f"Active control frames:     {active_control_frames}\n")
        f.write(f"Target EEF X:              {target_eef_x:+.6f} m\n")
        f.write(f"X Kp / max / deadband:     {pregrasp_kp_x:.3f} / {pregrasp_max_correction:.3f} / {pregrasp_deadband_m * 1000:.1f} mm\n")
        f.write(f"Initial/final X error:     {finite_or_na(initial_x_error, 100, 2, True)} / {finite_or_na(final_x_error, 100, 2, True)} cm\n")
        f.write(f"Minimum |X error|:         {finite_or_na(minimum_x_error, 100, 2)} cm\n")
        f.write(f"Maximum |X correction|:    {finite_or_na(maximum_x_correction, 1, 3)}\n")
        f.write(f"Target EEF Z:              {target_eef_z:+.6f} m\n")
        f.write(f"Z Kp / max / deadband:     {pregrasp_kp_z:.3f} / {pregrasp_max_z_correction:.3f} / {pregrasp_z_deadband_m * 1000:.1f} mm\n")
        f.write(f"Initial/final Z error:     {finite_or_na(initial_z_error, 100, 2, True)} / {finite_or_na(final_z_error, 100, 2, True)} cm\n")
        f.write(f"Minimum |Z error|:         {finite_or_na(minimum_z_error, 100, 2)} cm\n")
        f.write(f"Maximum |Z correction|:    {finite_or_na(maximum_z_correction, 1, 3)}\n\n")

        f.write("ROBOT END-EFFECTOR\n" + "-" * 68 + "\n")
        f.write(f"Initial EEF XYZ {initial_eef_pos}\n")
        f.write(f"Final EEF XYZ {final_eef_pos}\n")
        f.write(f"Maximum |dX| / |dY| / |dZ|: {finite_or_na(max_eef_dx, 100, 2)} / {finite_or_na(max_eef_dy, 100, 2)} / {finite_or_na(max_eef_dz, 100, 2)} cm\n\n")

        f.write("TUMBLER / OBJECT\n" + "-" * 68 + "\n")
        f.write(f"Initial tumbler XYZ {initial_tumbler_pos}\n")
        f.write(f"Maximum tumbler lift:      {finite_or_na(maximum_tumbler_lift, 100, 2)} cm\n")
        f.write(f"Minimum EEF-object dist:   {finite_or_na(minimum_eef_object_distance, 100, 2)} cm\n")
        f.write(f"Closest approach frame:    {frame_or_na(closest_approach_frame)}\n\n")

        if closest_eef_pos is not None and closest_tumbler_pos is not None:
            offset = closest_tumbler_pos - closest_eef_pos
            f.write("CLOSEST EEF-OBJECT GEOMETRY\n" + "-" * 68 + "\n")
            f.write(f"EEF XYZ:                   {np.array2string(closest_eef_pos, precision=4)}\n")
            f.write(f"Tumbler XYZ:               {np.array2string(closest_tumbler_pos, precision=4)}\n")
            f.write(f"Object minus EEF XYZ:      [{offset[0] * 100:+.2f}, {offset[1] * 100:+.2f}, {offset[2] * 100:+.2f}] cm\n")
            f.write(f"Horizontal XY offset:      {np.linalg.norm(offset[:2]) * 100:.2f} cm\n\n")

        if diagnostic["available"]:
            f.write("FINGER-PAD GEOMETRY\n" + "-" * 68 + "\n")
            for side in ("left", "right"):
                f.write(f"{side.capitalize()} closest frame:     {diagnostic[f'{side}_closest_frame']}\n")
                f.write(f"{side.capitalize()} pad XYZ:           {np.array2string(diagnostic[f'{side}_pad_xyz'], precision=4)}\n")
                f.write(f"{side.capitalize()} pad-center dist:   {diagnostic[f'min_{side}_pad_dist'] * 100:.2f} cm\n")
                f.write(f"{side.capitalize()} horiz-to-axis:     {diagnostic[f'{side}_horizontal_to_axis'] * 100:.2f} cm\n")
                f.write(f"{side.capitalize()} vertical offset:   {diagnostic[f'{side}_vertical_offset'] * 100:+.2f} cm\n")
                f.write(f"{side.capitalize()} surface clearance: {diagnostic[f'{side}_surface_clearance'] * 100:.2f} cm\n\n")
            f.write(f"Glass diameter:            {diagnostic['glass_diameter'] * 100:.2f} cm\n")
            f.write(f"Minimum pad separation:    {finite_or_na(diagnostic.get('min_pad_separation_episode', np.nan), 100, 2)} cm\n")
            f.write(f"Minimum separation frame:  {frame_or_na(diagnostic.get('min_pad_separation_frame', -1))}\n\n")

        f.write("PHYSICAL OUTCOME\n" + "-" * 68 + "\n")
        f.write(f"Contact occurred:          {yes_no(contact_occurred)}\n")
        f.write(f"First contact frame:       {frame_or_na(first_contact_frame)}\n")
        f.write(f"Grasp occurred:            {yes_no(grasp_occurred)}\n")
        f.write(f"First grasp frame:         {frame_or_na(first_grasp_frame)}\n")
        f.write(f"Lift success:              {yes_no(lift_success) if lift_success is not None else 'UNAVAILABLE'}\n")

    print(f"[+] Saved replay metrics: {metrics_path}")

    # -------------------------------------------------------------------------
    # 12. SAVE REPLAY DATASET
    # -------------------------------------------------------------------------
    if output_dataset_path:
        output_dataset = Path(output_dataset_path)
        output_dataset.parent.mkdir(parents=True, exist_ok=True)

        np.savez_compressed(
            output_dataset,
            sim_frames=np.asarray(sim_frames, dtype=np.uint8),
            human_frames=human_frames if human_frames is not None else np.empty((0,), dtype=np.uint8),
            source_actions=source_actions,
            actions=executed_actions,
            executed_actions=executed_actions,
            closed_loop_x_error=x_errors,
            closed_loop_x_correction=x_corrections,
            closed_loop_z_error=z_errors,
            closed_loop_z_correction=z_corrections,
            closed_loop_active=control_active_mask.astype(np.int8),
            robot_eef_pos=eef_positions,
            robot_eef_frames=eef_position_frames,
            tumbler_positions=tumbler_positions,
            tumbler_position_frames=tumbler_position_frames,
            left_pad_positions=left_pad_positions,
            right_pad_positions=right_pad_positions,
            contact_flags=contact_flags,
            grasp_flags=grasp_flags,
            rewards=rewards,
            initial_eef_pos=initial_eef_pos if initial_eef_pos is not None else np.full(3, np.nan, dtype=np.float32),
            initial_tumbler_pos=initial_tumbler_pos if initial_tumbler_pos is not None else np.full(3, np.nan, dtype=np.float32),
            max_tumbler_lift=np.float32(maximum_tumbler_lift),
            min_eef_tumbler_distance=np.float32(minimum_eef_object_distance),
            lift_success=np.int8(-1 if lift_success is None else int(lift_success)),
            replay_fps=np.float32(replay_fps),
            closed_loop_pregrasp=np.int8(int(closed_loop_pregrasp)),
            target_eef_x=np.float32(target_eef_x),
            pregrasp_kp_x=np.float32(pregrasp_kp_x),
            pregrasp_max_correction=np.float32(pregrasp_max_correction),
            pregrasp_deadband_m=np.float32(pregrasp_deadband_m),
            target_eef_z=np.float32(target_eef_z),
            pregrasp_kp_z=np.float32(pregrasp_kp_z),
            pregrasp_max_z_correction=np.float32(pregrasp_max_z_correction),
            pregrasp_z_deadband_m=np.float32(pregrasp_z_deadband_m),
            pregrasp_control_start_frac=np.float32(pregrasp_control_start_frac),
            entry_frame=np.int32(entry_frame),
            pregrasp_control_start_frame=np.int32(pregrasp_control_start),
            commanded_grasp_frame=np.int32(commanded_grasp_frame),
        )

        print(f"[+] Saved paired replay dataset: {output_dataset}")

    create_comparison_video(np.asarray(sim_frames, dtype=np.uint8), human_frames, output_video_path, replay_fps)

